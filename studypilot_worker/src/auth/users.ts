  password: string;
  is_active: boolean;
  username: string | null;
  email: string;
  full_name: string;
  role: string;
  profile_completed: boolean;
  matric_number: string;
  faculty: string;
  department: string;
  level: string;
  semester: string;
  institution: string;
  current_courses: unknown;
  academic_goal: unknown;
  weak_courses: unknown;
  preferred_learning_style: string;
  preferred_resource_types: unknown;
  study_hours_per_week: number | null;
  exam_preparation_focus: string;
  career_interest: string;
  avatar: string;
  date_joined: Date;
  google_id: string;
  supabase_user_id: string;
  is_google_account: boolean;
  sui_address: string | null;
